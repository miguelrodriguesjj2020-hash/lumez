import {readFile, writeFile, mkdir} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
import vm from 'node:vm';

const root = fileURLToPath(new URL('..', import.meta.url));
const check = process.argv.includes('--check');
const read = relative => readFile(path.join(root, relative), 'utf8');
const pkg = JSON.parse(await read('package.json'));
const sources = JSON.parse(await read('src/sources.json'));
const core = await read('src/core.js');
const provider = await read('src/provider.js');
if (!core.includes(`var VERSION = '${pkg.version}';`)) throw new Error('Version mismatch');
if (new Set(sources.map(s => s.scraperId)).size !== sources.length) throw new Error('Duplicate scraper IDs');

const bundle = `// Aurora PT-BR ${pkg.version} — MIT. Generated by scripts/build.mjs.\n(function(root) {\n'use strict';\nfunction localModule(factory) { var module = {exports:{}}; factory(module, module.exports); return module.exports; }\nvar core = localModule(function(module, exports) {\n${core}\n});\nvar createProvider = localModule(function(module, exports) {\n${provider}\n});\nvar plugin = createProvider(core, ${JSON.stringify(sources)}, root);\nif (typeof module !== 'undefined') module.exports = plugin;\nroot.getStreams = plugin.getStreams;\nroot.onSettings = plugin.onSettings;\n})(typeof globalThis !== 'undefined' ? globalThis : this);\n`;
new vm.Script(bundle, {filename: 'aurora.js'});
const manifest = {
  name: 'Aurora PT-BR', version: pkg.version,
  description: 'Dublado e português informado por fontes independentes. Usa seus catálogos atuais.',
  author: 'miguelrodriguesjj2020-hash',
  scrapers: sources.map(source => ({
    id: source.scraperId, name: 'Aurora · ' + source.name,
    description: 'Áudio informado pela fonte; reprodução e variante não são garantidas. Filmes e episódios dos catálogos existentes.',
    version: pkg.version, filename: 'providers/aurora.js', supportedTypes: ['movie', 'tv'],
    enabled: true, hasSettings: true, contentLanguage: ['pt-BR', 'pt'],
    formats: ['hls', 'mp4', 'mkv'], supportsExternalPlayer: true
  }))
};
const outputs = new Map([
  ['providers/aurora.js', bundle],
  ['manifest.json', JSON.stringify(manifest, null, 2) + '\n']
]);
for (const [name, content] of outputs) {
  if (check) {
    if (await read(name).catch(() => '') !== content) throw new Error(`${name} is stale; run npm run build`);
  } else {
    await mkdir(path.dirname(path.join(root, name)), {recursive: true});
    await writeFile(path.join(root, name), content);
  }
}
console.log(check ? 'Manifest and bundle match source.' : `Built Aurora ${pkg.version}: ${sources.length} independent providers.`);
